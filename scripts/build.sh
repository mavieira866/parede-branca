#!/usr/bin/env bash

###############################################################################
# Parede Branca
#
# Script de compilação
#
# Autor: Marcos Vieira
# Projeto: Parede Branca
###############################################################################

set -euo pipefail

###############################################################################
# Configuração
###############################################################################

PROJECT_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUTPUT_DIR="${PROJECT_ROOT}/build/pdf"
MAIN_FILE="${PROJECT_ROOT}/documento.tex"

ENGINE="xelatex"

###############################################################################
# Cores
###############################################################################

GREEN="\033[0;32m"
YELLOW="\033[1;33m"
RED="\033[0;31m"
BLUE="\033[0;34m"
NC="\033[0m"

###############################################################################
# Funções
###############################################################################

info() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

success() {
    echo -e "${GREEN}[OK]${NC} $1"
}

warning() {
    echo -e "${YELLOW}[WARN]${NC} $1"
}

error() {
    echo -e "${RED}[ERRO]${NC} $1"
}

###############################################################################
# Verificação
###############################################################################

check_command() {
    if ! command -v "$1" >/dev/null 2>&1; then
        error "Comando '$1' não encontrado."
        exit 1
    fi
}

###############################################################################
# Dependências
###############################################################################

info "Verificando dependências..."

check_command latexmk
check_command "$ENGINE"

success "Dependências encontradas."

###############################################################################
# Diretórios
###############################################################################

mkdir -p "$OUTPUT_DIR"

###############################################################################
# Limpeza
###############################################################################

info "Removendo arquivos temporários..."

latexmk -C "$MAIN_FILE" >/dev/null 2>&1 || true

###############################################################################
# Compilação
###############################################################################

info "Compilando livro..."

latexmk \
    -interaction=nonstopmode \
    -file-line-error \
    -xelatex \
    -output-directory="$OUTPUT_DIR" \
    "$MAIN_FILE"

###############################################################################
# Resultado
###############################################################################

PDF="${OUTPUT_DIR}/livro.pdf"

if [[ -f "$PDF" ]]; then

    success "PDF gerado com sucesso!"

    echo
    echo "Arquivo:"
    echo "  $PDF"

else

    error "Falha na geração do PDF."

    exit 1

fi